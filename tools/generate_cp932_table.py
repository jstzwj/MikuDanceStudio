"""Generate the checked-in Windows-31J decode map using Python's CP932 codec.

The map is Unicode character mapping data, generated deterministically; it is
not a copy of the codec implementation. No Python dependency exists at runtime.
"""
from pathlib import Path


def generate():
    singles = []
    pairs = []
    for byte in range(256):
        try:
            singles.append(ord(bytes([byte]).decode('cp932')))
        except UnicodeDecodeError:
            singles.append(0xffffffff)
    # Windows MB_ERR_INVALID_CHARS rejects these vendor single-byte aliases,
    # although Python maps them to U+F8F0..U+F8F3. Keep strict imports identical
    # on every platform; the native exhaustive test verifies this policy.
    for byte in (0xa0, 0xfd, 0xfe, 0xff):
        singles[byte] = 0xffffffff
    for lead in range(256):
        if singles[lead] != 0xffffffff:
            continue
        for trail in range(256):
            try:
                value = bytes([lead, trail]).decode('cp932')
            except UnicodeDecodeError:
                continue
            if len(value) == 1:
                pairs.append(((lead << 8) | trail, ord(value)))
    lines = ['// Generated by tools/generate_cp932_table.py. Do not edit.',
             'static constexpr std::uint32_t Cp932Single[256]{']
    for begin in range(0, 256, 8):
        lines.append('    ' + ','.join(f'0x{x:08x}' for x in singles[begin:begin + 8]) + ',')
    lines += ['};', 'struct Cp932Pair { std::uint16_t bytes, unicode; };',
              'static constexpr Cp932Pair Cp932Pairs[]{']
    for begin in range(0, len(pairs), 6):
        lines.append('    ' + ','.join(f'{{0x{b:04x},0x{u:04x}}}' for b, u in pairs[begin:begin + 6]) + ',')
    lines += ['};', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[1] / 'src/io/cp932_decode_table.inc'
    expected = generate()
    if args.check:
        if target.read_text(encoding='utf-8') != expected:
            raise SystemExit('CP932 mapping differs from the reviewed codec mapping')
        print('CP932 mapping matches the deterministic generator')
    else:
        target.write_text(expected, encoding='utf-8')
