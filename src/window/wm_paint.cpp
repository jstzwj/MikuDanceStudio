//   this+736   timeline strip  -> (6, 95)          w = sidebar-10  h = 50
//   this+724   main panel      -> (6, 145)         w = sidebar-25  h = bottom-393
//   this+744   interp curve    -> (8, bottom-135)  128x128
//
// Deviation note: the original repeats each label as a full 10-argument
// sub_40E290 (DrawGlyph) call; the port factors the invariable colour
// arguments (this+656852/53/54, flag 0) into a local Lbl() wrapper.
// Every call site keeps its exact string/size/coordinate arguments.
